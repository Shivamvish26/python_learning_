# Use type() to identify the data type of each variable.

a = 10
b = 10.5
c = "Hello"
d = True
e = [1, 2, 3]
f = (1, 2, 3)
g = {1, 2, 3}
h = {"name": "Shivam"}

print(type(a)) #int
print(type(b)) #float
print(type(c)) #String
print(type(d)) #Boolean
print(type(e)) #list
print(type(f)) #tuple
print(type(g)) #set
print(type(h)) #dictionary