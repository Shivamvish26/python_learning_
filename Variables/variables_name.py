# camel case
myVariableName = "Shivam"
print(myVariableName)
# shivam [each word, except the first, every letter word start with cap.]

# pascal case
MyVariableName = "Shubham"
print(MyVariableName)
# Shubham [each & every word start with cap. letter]

# snake case
my_Variable_Name = "Shubs"
print(my_Variable_Name)
#  Shubs [it contain the  "_ undercorse" between the word]