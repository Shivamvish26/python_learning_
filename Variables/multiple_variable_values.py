# Multiple values assign
x, y, z = "Banana", "Orange", "Mango"
print(x)
print(y)
print(z)

# one value to multiple variables
x = y = z = "Orange"
print(x)
print(y)
print(z)

# unpacking the variables
# the collection can be used with the help of list, tuples, etc
fruits = ["Mango", "banana", "orange"]
x, y, z = fruits
print(x)
print(y)
print(z)